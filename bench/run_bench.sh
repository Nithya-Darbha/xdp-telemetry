#!/usr/bin/env bash
# Controlled experiment: drive a fixed offered load through mon0 and measure
# each capture engine. Writes one CSV row per (engine, load).
#
#   sudo bench/run_bench.sh [bench/results.csv]
#
# Engines compared:
#   none        no monitor (control: cost of the traffic path alone)
#   xdp         XDP native
#   xdp-generic XDP generic (skb) mode
#   afp1        AF_PACKET baseline, 1 thread
#   afp2        AF_PACKET baseline, 2 threads
#
# Metrics per run:
#   offered_pps   what the generator aimed to send
#   proc_pps      packets the monitor actually accounted for (median window)
#   cpu_pct       system-wide busy % during the load (all cores, /proc/stat)
#   ns_per_pkt    XDP only: run_time_ns/run_cnt from bpf_stats
#   drops         AF_PACKET ring-overflow drops (0 or n/a otherwise)
#
# Caveats are real and belong in the README: this runs over veth (no driver
# XDP win over skb allocation), in whatever VM you run it in, and the load is
# generated by iperf3 in userspace, so absolute pps is modest. The comparison
# between engines at the same offered load is the signal, not the absolute pps.
set -u

CSV="${1:-bench/results.csv}"
DUR="${DUR:-6}"            # seconds of load per run
PKTLEN="${PKTLEN:-200}"    # UDP payload bytes
LOADS_MBPS="${LOADS_MBPS:-100 400 800}"
MON_IP=10.77.0.2
BPFTOOL="${BPFTOOL:-$(for c in /usr/lib/linux-tools/*/bpftool $(command -v bpftool); do "$c" version >/dev/null 2>&1 && { echo "$c"; break; }; done)}"
XDPT=./build/xdpt
AFP=./build/xdpt-afp

[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
ip netns exec xdpt-gen true 2>/dev/null || { echo "bring up scripts/netns.sh up first" >&2; exit 1; }

cpu_busy_snapshot() { read -r _ a b c d e f g h _ < /proc/stat; echo "$((a+b+c+e+f+g+h)) $((a+b+c+d+e+f+g+h))"; }

echo "engine,offered_mbps,offered_pps,proc_pps,cpu_pct,ns_per_pkt,drops" > "$CSV"

run_one() {
  local engine="$1" mbps="$2" jf mon_pid="" cpu0 cpu1 b0 t0 b1 t1
  local offered_pps=$(( mbps * 1000000 / 8 / PKTLEN ))
  jf=$(mktemp)

  # UDP sink on the monitored host so frames actually arrive at mon0
  ip netns exec xdpt-mon iperf3 -s -1 -p 5201 >/dev/null 2>&1 &
  local srv=$!
  sleep 0.3

  case "$engine" in
    xdp)         ip netns exec xdpt-mon "$XDPT" -i mon0 -m native  -w 1000 -j "$jf" >/dev/null 2>&1 & mon_pid=$!;;
    xdp-generic) ip netns exec xdpt-mon "$XDPT" -i mon0 -m generic -w 1000 -j "$jf" >/dev/null 2>&1 & mon_pid=$!;;
    afp1)        ip netns exec xdpt-mon "$AFP"  -i mon0 -t 1 -w 1000 -j "$jf" >/dev/null 2>&1 & mon_pid=$!;;
    afp2)        ip netns exec xdpt-mon "$AFP"  -i mon0 -t 2 -w 1000 -j "$jf" >/dev/null 2>&1 & mon_pid=$!;;
    none)        : ;;
  esac
  sleep 1

  read -r b0 t0 <<<"$(cpu_busy_snapshot)"
  ip netns exec xdpt-gen iperf3 -u -c "$MON_IP" -p 5201 -b "${mbps}M" -l "$PKTLEN" -t "$DUR" >/dev/null 2>&1
  read -r b1 t1 <<<"$(cpu_busy_snapshot)"

  local cpu_pct="0"
  [ "$((t1-t0))" -gt 0 ] && cpu_pct=$(awk "BEGIN{printf \"%.1f\",100*($b1-$b0)/($t1-$t0)}")

  local ns_per_pkt="" drops=""
  if [ "$engine" = xdp ] || [ "$engine" = xdp-generic ]; then
    ns_per_pkt=$("$BPFTOOL" -j prog show name xdpt_main 2>/dev/null | \
      python3 -c "import json,sys
try:
 d=json.load(sys.stdin); d=d[0] if isinstance(d,list) else d
 rt=d.get('run_time_ns',0); rc=d.get('run_cnt',0)
 print(round(rt/rc,1) if rc else '')
except Exception: print('')" 2>/dev/null)
  fi

  local proc_pps=0
  if [ -n "$mon_pid" ]; then
    kill -INT "$mon_pid" 2>/dev/null; wait "$mon_pid" 2>/dev/null
    proc_pps=$(python3 -c "import json,sys,statistics as st
v=[]
d=[]
for l in open('$jf'):
 l=l.strip()
 if not l.startswith('{'): continue
 try: o=json.loads(l)
 except: continue
 if 'pps' in o and o.get('pps',0)>0: v.append(o['pps'])
 if 'drops' in o: d.append(o['drops'])
print(int(st.median(v)) if v else 0, max(d) if d else 0)" 2>/dev/null)
    drops=$(echo "$proc_pps" | awk '{print $2}'); proc_pps=$(echo "$proc_pps" | awk '{print $1}')
  fi

  kill "$srv" 2>/dev/null; wait "$srv" 2>/dev/null; rm -f "$jf"
  echo "$engine,$mbps,$offered_pps,$proc_pps,$cpu_pct,${ns_per_pkt:-},${drops:-}" | tee -a "$CSV"
}

echo 1 > /proc/sys/kernel/bpf_stats_enabled
for mbps in $LOADS_MBPS; do
  for eng in none xdp xdp-generic afp1 afp2; do
    run_one "$eng" "$mbps"
  done
done
echo 0 > /proc/sys/kernel/bpf_stats_enabled
echo "wrote $CSV"
